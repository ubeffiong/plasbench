#!/usr/bin/env python3
"""The facet heatmaps and the presence matrix in a built report: the offline demo (synthetic) and the real 10-isolate cohort (results_real_cohort1, 0.2.3).

  demo     both sections are on the page in their views, carry data, a static figure, a collapsed table and the green ? help; every inline script parses; the added size is bounded
  cohort1  the facet heatmaps draw from the score table and the sample tables (there are no per-sample folders in that run), so no plasmid-level data; the presence matrix has no
           truth tables and says so, in the Run metadata list (a section that holds only a Not-run notice is moved there by the report)

The demo is built from a copy of results_demo (generated by test/run_demo.sh); without it the demo half is skipped with the reason printed.
"""
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PY = ROOT / "python"
sys.path.insert(0, str(ROOT / "test"))
import test_report_javascript as tj  # noqa: E402

BUDGET_BYTES = 420_000          # what the two sections may add to the demo report (JSON, static figures, tables, scripts, styles)


def build(args, out):
    return subprocess.run([sys.executable, str(PY / "build_html_report.py"), "--project-root", str(ROOT), *args, "--out", str(out)], capture_output=True, text=True)


def section(page, sid):
    i = page.find(f"<section id='{sid}'")
    return "" if i < 0 else page[i:page.find("</section>", i)]


def main():
    ok = True

    def check(label, condition, detail=""):
        nonlocal ok
        ok &= bool(condition)
        print(f"  {'PASS' if condition else 'FAIL'}: {label}" + (f"  {detail}" if detail and not condition else ""))

    demo_src = ROOT / "results_demo"
    print("the offline demo")
    if not (demo_src / "scores.tsv").is_file():
        print("  SKIP: no results_demo folder (run test/run_demo.sh first); the demo half was not run")
    else:
        with tempfile.TemporaryDirectory() as work:
            d = Path(work) / "results"
            shutil.copytree(demo_src, d, ignore=shutil.ignore_patterns("benchmark.report.html"))
            p = lambda n: str(d / n)  # noqa: E731
            args = ["--scores", p("scores.tsv"), "--tool-status", p("tool_status.tsv"), "--leaderboard", p("benchmark.leaderboard.tsv"), "--sample-sheet", p("samples.tsv"),
                    "--recommendations", p("benchmark.recommendations.tsv"), "--manifest", p("run_manifest.json"), "--recovery-by-replicon", p("benchmark.recovery_by_replicon.tsv"),
                    "--dataset-features", p("benchmark.dataset_features.tsv"), "--dimensions-prefix", p("benchmark"), "--comparisons", p("benchmark.paired_comparisons.tsv"),
                    "--stratified", p("benchmark.stratified.tsv"), "--rank-robustness", p("benchmark.rank_robustness.tsv"), "--data-dir", str(d),
                    "--truth-provenance", p("benchmark.truth_provenance.tsv"), "--outcome-states", p("benchmark.outcome_states.tsv"), "--amr-placement", p("benchmark.amr_placement.tsv")]
            run = build(args, d / "benchmark.report.html")
            check("the demo report builds", run.returncode == 0, run.stderr[-600:])
            if run.returncode == 0:
                page = (d / "benchmark.report.html").read_text(encoding="utf-8")
                views = {m.group(1): m.start() for m in re.finditer(r"id='view-([a-z]+)'", page)}
                order = sorted(views.items(), key=lambda kv: kv[1])
                def view_of(pos):
                    name = None
                    for n, start in order:
                        if start <= pos:
                            name = n
                    return name
                for sid, view in (("fig-facets", "figures"), ("fig-presence", "figures")):
                    seg = section(page, sid)
                    check(f"{sid} is in the page, in the {view} view", bool(seg) and view_of(page.find(f"<section id='{sid}'")) == view)
                    check(f"{sid} has its green ? help and no Not-run notice", f"data-help='{sid}'" in page and "<div class='insight caution'>" not in seg)
                    check(f"{sid} keeps the table available as a collapsed fold", re.search(r"<details class='rpt-collapsible [a-z]+-table' data-closed><summary>Table:", seg) is not None)
                    check(f"{sid} has a static figure for print", "class='rpt-figure" in seg and "<svg" in seg)
                fd = json.loads(re.search(r"id='fc-data'>(.*?)</script>", section(page, "fig-facets"), re.S).group(1).replace("\\u003c", "<").replace("\\u003e", ">").replace("\\u0026", "&"))
                check("the facet data hold the isolate and the plasmid level", set(fd["levels"]) == {"isolate", "plasmid"}, list(fd["levels"]))
                pdat = json.loads(re.search(r"id='fp-data'>(.*?)</script>", section(page, "fig-presence"), re.S).group(1).replace("\\u003c", "<").replace("\\u003e", ">").replace("\\u0026", "&"))
                check("the presence data hold the 11 demo truth plasmids and their blocks", len(pdat["rows"]) == 11 and len(pdat["blocks"]) >= 3, len(pdat["rows"]))
                scripts = tj.inline_scripts(page)
                broken = [i for i, body in enumerate(scripts, 1) if tj.unterminated_string(body)]
                check("no inline script has a string broken across lines", not broken, broken)
                node = shutil.which("node")
                if node:
                    bad = []
                    for i, body in enumerate(scripts, 1):
                        if "FCCore" in body or "FPCore" in body:
                            f = Path(work) / f"s{i}.js"
                            f.write_text(body, encoding="utf-8")
                            r = subprocess.run([node, "--check", str(f)], capture_output=True, text=True)
                            if r.returncode:
                                bad.append((i, r.stderr[:200]))
                    check("the scripts of both figures parse", not bad, bad)
                else:
                    print("  SKIP: node is not installed, so the figure scripts were not parsed")
                grown = len(section(page, "fig-facets")) + len(section(page, "fig-presence"))
                check(f"the two sections add less than {BUDGET_BYTES:,} bytes to the demo report", grown < BUDGET_BYTES, f"{grown:,}")
                print(f"  INFO: fig-facets {len(section(page, 'fig-facets')):,} bytes, fig-presence {len(section(page, 'fig-presence')):,} bytes of {len(page):,}")
                check("the demo page says its data are synthetic", "synthetic" in page.lower())

    print("the real cohort (results_real_cohort1)")
    cohort = ROOT / "results_real_cohort1"
    if not (cohort / "scores.tsv").is_file():
        print("  SKIP: results_real_cohort1 is absent")
    else:
        with tempfile.TemporaryDirectory() as work:
            r = Path(work) / "results_real_cohort1"
            shutil.copytree(cohort, r, ignore=shutil.ignore_patterns("benchmark.report.html"))
            pre = str(r / "benchmark")
            args = ["--scores", str(r / "scores.tsv"), "--tool-status", str(r / "tool_status.tsv"), "--leaderboard", pre + ".leaderboard.tsv", "--manifest", str(r / "run_manifest.json"),
                    "--comparisons", pre + ".paired_comparisons.tsv", "--score-failures", str(r / "score_failures.tsv"), "--recommendations", pre + ".recommendations.tsv",
                    "--dimensions-prefix", pre, "--stratified", pre + ".stratified.tsv", "--rank-robustness", pre + ".rank_robustness.tsv", "--truth-provenance", pre + ".truth_provenance.tsv",
                    "--outcome-states", pre + ".outcome_states.tsv"]
            run = build(args, r / "benchmark.report.html")
            check("the cohort report builds", run.returncode == 0, run.stderr[-600:])
            if run.returncode == 0:
                page = (r / "benchmark.report.html").read_text(encoding="utf-8")
                seg = section(page, "fig-facets")
                check("the facet heatmaps are on the page", bool(seg))
                m = re.search(r"id='fc-data'>(.*?)</script>", seg, re.S)
                fd = json.loads(m.group(1).replace("\\u003c", "<").replace("\\u003e", ">").replace("\\u0026", "&")) if m else {}
                check("they hold the isolate level only (no per-sample folders in this run)", list(fd.get("levels", {})) == ["isolate"], list(fd.get("levels", {})))
                check("they hold the 10 isolates and the 4 tools, ordered as the leaderboard", len(fd["levels"]["isolate"]["units"]) == 10 and [t[1] for t in fd["tools"]][0] == "mob_recon")
                check("the strata come from the recorded tables (species, depth, tier, study, origin)", {"species", "depth", "tier", "study", "origin"} <= {s["k"] for s in fd["levels"]["isolate"]["strata"]})
                check("no tool, isolate or cell is invented: every value is null or a number between 0 and 1 (or a [correct, total] pair)",
                      all(v is None or (isinstance(v, list) and 0 <= v[0] <= v[1]) or 0 <= v <= 1 for t in fd["levels"]["isolate"]["vals"].values() for arr in t.values() for v in arr))
                check("the presence matrix is not drawn: no truth tables in this run", "<section id='fig-presence'" not in page)
                reasons = re.sub(r"<[^>]+>", " ", page[page.find("Not run in this run"):][:200000])
                check("the reason is listed once, in Run metadata, as 'Not available in this run: ...' naming the missing tables",
                      "Not available in this run: the per-sample truth tables" in reasons and "--data-dir" in reasons, reasons[:300])
                check("no path of the machine that made the run appears", "/home/" not in seg)
    print()
    if not ok:
        print("VISUALS BUILD TESTS FAILED")
        sys.exit(1)
    print("ALL VISUALS BUILD TESTS PASSED")


if __name__ == "__main__":
    main()
