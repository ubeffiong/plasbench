#!/usr/bin/env python3
"""`[output] format = auto` (python/user_tool_detect.py): files and folders are recognised by CONTENT, deterministically,
and an ambiguous or unrecognisable output is an error that lists what was seen, never a silent guess."""

import gzip
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "python"))

import user_tool_detect as det  # noqa: E402

FAILED = []


def check(name, ok, detail=""):
    print(("  ok    " if ok else "  FAIL  ") + name + ("" if ok else f"  [{detail}]"))
    if not ok:
        FAILED.append(name)


MOB_REPORT = ("sample_id\tmolecule_type\tprimary_cluster_id\tsecondary_cluster_id\tcontig_id\tsize\tgc\tmd5\trep_type(s)\n"
              "S1\tchromosome\t-\t-\tNODE_1\t2000000\t0.5\tabc\t-\n"
              "S1\tplasmid\tAA123\tAB1\tNODE_2\t5000\t0.45\tdef\tIncFIB\n"
              "S1\tplasmid\tAA123\tAB1\tNODE_3\t3000\t0.46\tghi\t-\n")
HUNTER = ("ID\tPrediction\tProbability\n"
          "NODE_1\tchromosome\t0.04\nNODE_2\tplasmid\t0.97\nNODE_3\tplasmid\t0.81\n")
FASTA = ">p1 plasmid one\nACGTACGTAC\nACGT\n>p2\nGGGGCCCC\n"


def main():
    with tempfile.TemporaryDirectory() as tmp:
        base = Path(tmp)

        def put(name, text, mode="w"):
            path = base / name
            path.parent.mkdir(parents=True, exist_ok=True)
            if mode == "gz":
                path.write_bytes(gzip.compress(text.encode()))
            else:
                path.write_text(text, encoding="utf-8", newline="\n")
            return path

        print("single files")
        d = det.detect(put("contig_report.txt", MOB_REPORT))
        formats = [r["format"] for r in d["roles"]]
        bins_role = next(r for r in d["roles"] if r["format"] == "contig_bins")
        labels_role = next(r for r in d["roles"] if r["format"] == "contig_labels")
        check("MOB-recon style contig_report serves bins AND labels", formats == ["contig_bins", "contig_labels"], d)
        check("... the contig column is contig_id (not sample_id), the bin column primary_cluster_id",
              bins_role["contig_column"] == "contig_id" and bins_role["bin_column"] == "primary_cluster_id", bins_role)
        check("... '-' is a no-bin value so chromosome contigs are not one giant bin", "-" in bins_role["bin_none_values"].split(","))
        check("... molecule_type is the label column with 'plasmid' as the plasmid value",
              labels_role["label_column"] == "molecule_type" and labels_role["plasmid_values"] == "plasmid", labels_role)
        d = det.detect(put("hunter.tsv", HUNTER))
        role = d["roles"][0]
        check("PlasmidHunter style table with probabilities is contig_labels with a score column",
              d["kind"] == "contig_labels" and role["contig_column"] == "ID" and role["label_column"] == "Prediction"
              and role["score_column"] == "Probability", d)
        d = det.detect(put("p.fasta", FASTA))
        check("a FASTA file is plasmid_fasta", d["kind"] == "plasmid_fasta", d)
        check("a gzipped FASTA is read through", det.detect(put("p2.fa.gz", FASTA, "gz"))["kind"] == "plasmid_fasta")
        d = det.detect(put("commented.csv", "# generated by mytool 1.2\n# run 2024\ncontig,bin\nc1,B1\nc2,B1\nc3,B2\n"))
        check("a comma table whose header follows comment lines is contig_bins",
              d["kind"] == "contig_bins" and d["table"]["delimiter"] == "," and d["roles"][0]["bin_column"] == "bin", d)
        d = det.detect(put("hashheader.tsv", "#contig\tbin\nc1\tB1\nc2\tB2\n"))
        check("a header that itself starts with '#' is recognised", d["kind"] == "contig_bins" and d["roles"][0]["contig_column"] == "contig", d)
        d = det.detect(put("semi.csv", "contig;prediction;score\nc1;plasmid;0.9\nc2;chromosome;0.1\n"))
        check("a semicolon table is recognised", d["kind"] == "contig_labels" and d["table"]["delimiter"] == ";", d)
        d = det.detect(put("headerless.tsv", "c1\tB1\nc2\tB1\nc3\tB2\n"))
        check("a headerless two-column table of ids and bin names is contig_bins by column number",
              d["kind"] == "contig_bins" and d["roles"][0]["contig_column"] == "1" and d["roles"][0]["bin_column"] == "2", d)
        d = det.detect(put("headerless_labels.tsv", "c1\tplasmid\nc2\tchromosome\n"))
        check("... and plasmid/chromosome words make it contig_labels", d["kind"] == "contig_labels", d)
        empty = put("empty.tsv", "")
        d = det.detect(empty)
        check("an empty file is not recognised and says so", d["kind"] is None and "empty" in d["why"], d)
        d = det.detect(put("notes.txt", "this run finished OK\nthanks\n"))
        check("free text is not recognised and the first line is shown", d["kind"] is None and "this run finished OK" in d["why"], d)
        d = det.detect(put("odd.tsv", "foo\tbar\n1\t2\n"))
        check("a table without a contig-id column is not recognised, naming its columns", d["kind"] is None and "foo, bar" in d["why"], d)
        d = det.detect(put("ids_only.tsv", "contig\tlength\nc1\t100\nc2\t200\n"))
        check("a contig table with no bin/label/probability column is not recognised", d["kind"] is None and "no bin/cluster" in d["why"], d)
        check("a missing path is reported", det.detect(base / "nope")["why"] == "does not exist")

        print("folders")
        put("bins/plasmid_1.fasta", ">a\nACGT\n")
        put("bins/plasmid_2.fa", ">b\nACGT\n")
        d = det.detect(base / "bins")
        check("a folder with several FASTA files is fasta_dir", d["kind"] == "fasta_dir" and len(d["files"]) == 2, d)
        put("mixed/plasmid_1.fasta", ">a\nACGT\n")
        put("mixed/run.log", "log\n")
        put("mixed/contig_report.txt", MOB_REPORT)
        d = det.detect(base / "mixed")
        check("a mixed folder is fasta_dir, and the ignored non-FASTA files are named",
              d["kind"] == "fasta_dir" and "run.log" in d["why"] and "contig_report.txt" in d["why"], d)
        put("logs/a.log", "x\n")
        d = det.detect(base / "logs")
        check("a folder with no FASTA is not recognised and lists what it holds", d["kind"] is None and "a.log" in d["why"], d)

        print("candidates and the choice per task")
        out = base / "run1"
        put("run1/contig_report.txt", MOB_REPORT)
        put("run1/plasmid_AA123.fasta", ">NODE_2\nACGT\n")
        put("run1/plasmid_AB5.fasta", ">NODE_9\nACGT\n")
        found, unmatched = det.detect_all(out, ["contig_report.txt", "plasmid_*.fasta", "mobtyper*.txt"])
        check("a glob matching several FASTA files is one fasta_dir group; an unmatched pattern is reported",
              [d["kind"] for d in found] == ["contig_bins", "fasta_dir"] and len(found[1]["group"]) == 2 and unmatched == ["mobtyper*.txt"], (found, unmatched))
        det_b, role_b, note_b = det.choose(out, found, unmatched, "binning_reconstruction")
        check("binning <- contig_bins (native)", role_b["format"] == "contig_bins" and note_b == "")
        det_c, role_c, note_c = det.choose(out, found, unmatched, "classification")
        check("classification <- contig_labels (native) when the table has labels", role_c["format"] == "contig_labels" and note_c == "")
        det_r, role_r, _ = det.choose(out, found, unmatched, "sequence_reassembly")
        check("reassembly <- the FASTA group", role_r["format"] == "fasta_dir")

        only_bins = [{"path": str(out / "b.csv"), "kind": "contig_bins", "roles": [{"format": "contig_bins"}], "why": "bins table"}]
        _, role, note = det.choose(out, only_bins, [], "classification")
        check("classification <- contig_bins is derived (a contig in any bin is plasmid) and says so", role["format"] == "contig_bins" and "any bin" in note, note)
        only_labels = [{"path": str(out / "l.csv"), "kind": "contig_labels", "roles": [{"format": "contig_labels"}], "why": "labels table"}]
        _, role, note = det.choose(out, only_labels, [], "binning_reconstruction")
        check("binning <- contig_labels is derived and flagged as not a real grouping", role["format"] == "contig_labels" and "not a real grouping" in note, note)
        try:
            det.choose(out, only_bins, [], "sequence_reassembly")
            nothing = ""
        except det.NothingRecognised as exc:
            nothing = str(exc)
        check("reassembly cannot be derived from a bins table: an error listing what was seen",
              "sequence_reassembly" in nothing and "b.csv: bins table" in nothing, nothing)

        two = only_bins + [{"path": str(out / "b2.csv"), "kind": "contig_bins", "roles": [{"format": "contig_bins"}], "why": "another bins table"}]
        try:
            det.choose(out, two, [], "binning_reconstruction")
            amb = ""
        except det.AmbiguityError as exc:
            amb = str(exc)
        check("two candidates that could both be the bins are an ambiguity error naming both", "b.csv" in amb and "b2.csv" in amb and "Narrow" in amb, amb)
        found2, un2 = det.detect_all(out, ["nothing_here.txt"])
        try:
            det.choose(out, found2, un2, "classification")
            none = ""
        except det.NothingRecognised as exc:
            none = str(exc)
        check("no matching file is an error that names the pattern", "nothing_here.txt" in none, none)
        check("detection is deterministic (same input, same answer)",
              det.detect(out / "contig_report.txt") == det.detect(out / "contig_report.txt"))

    if FAILED:
        print("USER TOOL DETECT TESTS FAILED")
        return 1
    print("ALL USER TOOL DETECT TESTS PASSED")
    return 0


if __name__ == "__main__":
    sys.exit(main())
