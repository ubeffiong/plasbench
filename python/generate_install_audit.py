#!/usr/bin/env python3
"""Write docs/TOOL_INSTALL_AUDIT.md from the registries (config/tool_installers.tsv, config/metagenomic_tool_installers.tsv, config/source_tools.json).

`python python/generate_install_audit.py` rewrites the file; `--check` exits 1 when the file on disk is not what the registries produce (test/test_tool_install_registry.py
runs it), so the table cannot drift from the pins. Install times are 'not measured' unless a measurement is recorded in config/source_tools.json (`measured_minutes`)."""

from __future__ import annotations

import argparse
import csv
import json
import io
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "TOOL_INSTALL_AUDIT.md"

# Profiles installed from conda (env/install_tools.sh): what the script pins and where the package comes from. The versions are the ones written in the script itself.
CONDA_FACTS = {
    "reconstruction": ("conda: mob_suite=3.1.9 (own env, pandas<=1.5.3) + platon (bioconda, unpinned)", "https://bioconda.github.io/", "several GB", "10-30 min (not measured)"),
    "assembly": ("conda: spades, unicycler (bioconda, unpinned)", "https://bioconda.github.io/", "about 1 GB", "5-15 min (not measured)"),
    "long-read": ("conda: flye, mob_suite, filtlong (bioconda, unpinned)", "https://bioconda.github.io/", "about 1 GB", "5-15 min (not measured)"),
    "plassembler": ("conda: plassembler (bioconda, unpinned)", "https://bioconda.github.io/recipes/plassembler/README.html", "about 1 GB", "5-15 min (not measured)"),
    "hybracter": ("conda: hybracter (bioconda, unpinned)", "https://bioconda.github.io/recipes/hybracter/README.html", "about 2 GB", "5-20 min (not measured)"),
    "trycycler": ("conda, own env: trycycler flye medaka (bioconda, unpinned)", "https://bioconda.github.io/recipes/trycycler/README.html", "several GB (PyTorch)", "10-30 min (not measured)"),
    "genomad": ("conda: genomad (bioconda, unpinned)", "https://bioconda.github.io/recipes/genomad/README.html", "about 1 GB", "5-15 min (not measured)"),
    "rfplasmid": ("conda: rfplasmid, setuptools<81 (bioconda)", "https://bioconda.github.io/recipes/rfplasmid/README.html", "several GB (CheckM)", "10-30 min (not measured)"),
    "plasmidhunter": ("conda own env python 3.10 + pip plasmidhunter==1.4", "https://pypi.org/project/plasmidhunter/1.4/", "about 1 GB", "5-15 min (not measured)"),
    "plasmer": ("conda own env python 3.10: plasmer (channel iskoldt)", "https://anaconda.org/iskoldt/plasmer", "about 1 GB", "5-15 min (not measured)"),
    "plascope": ("conda own env python 3.6: plascope=1.3.1", "https://bioconda.github.io/recipes/plascope/README.html", "about 1 GB", "5-15 min (not measured)"),
    "baseline": ("built in (no install)", "-", "none", "none"),
}


def read_tsv(path: Path) -> list[dict]:
    with path.open(newline="", encoding="utf-8") as handle:
        return [{k: (v or "").strip() for k, v in row.items()} for row in csv.DictReader(handle, delimiter="\t")]


def build() -> str:
    rows = read_tsv(ROOT / "config" / "tool_installers.tsv") + read_tsv(ROOT / "config" / "metagenomic_tool_installers.tsv")
    registry = json.loads((ROOT / "config" / "source_tools.json").read_text(encoding="utf-8"))["profiles"]
    lines = [
        "# Tool installation audit",
        "",
        "<!-- Generated by python/generate_install_audit.py from config/tool_installers.tsv, config/metagenomic_tool_installers.tsv and config/source_tools.json. Do not edit by hand. -->",
        "",
        "What happens when a tool is enabled and a run, `plasbench check --yes`, `plasbench install-tools` or the window needs it, per tool. Revisions are 40-character commit",
        "SHAs resolved from the release tag on the date shown; a tag or branch name is never what is fetched. Times are estimates unless stated: nothing here was timed on a",
        "real conda solve. The *CI proof* column is what `.github/workflows/tool-install-proof.yml` showed on a clean Linux runner (config/install_proof_result.json).",
        "",
        "## How installation works now",
        "",
        "| Situation | Behaviour |",
        "| --- | --- |",
        "| `plasbench install-tools PROFILE --yes` | Installs the profile. A source-built tool shows its plan (repository, pinned commit, size, licence) first and needs `--yes` (or `y` at a terminal): without it nothing changes and the exit code is 21. |",
        "| `plasbench install-tools a,b,c --yes` | Several profiles in one command (the window's *Install all enabled tools*). |",
        "| Exit 20 | A tool that cannot be installed automatically (verified reason and recipe printed). Information, not a failure: no `ERROR`, not red, in the console, the terminal page, the window state and `scripts/lib.sh`. |",
        "| `plasbench run` / `check` with an enabled tool missing | Stage 0 lists every missing tool. At a terminal it asks; with `--yes`, `INSTALL_MISSING_TOOLS=1` or `plasbench run --install-missing-tools` it installs first and checks again in the same process (it no longer asks you to open a new shell); with no terminal and no consent it stops before any sample work, naming every missing tool and the exact command. |",
        "| Stage 4 reached with a tool still missing | One notice names every missing enabled tool; each is recorded as `skipped` with the reason `command unavailable (not installed; run: plasbench install-tools PROFILE --yes)`, never silently dropped. |",
        "| The window | *Install* / *Update* per tool on the Tools page and Workflow cards, *Install all enabled tools* (one consent dialog), a progress strip, and an offer to install missing enabled tools before a run starts. Tools are marked stale after an install so the next probe re-checks. |",
        "| `plasbench install-tools docker [--yes] [--dry-run] [--hello-world]` | Detects the computer (Windows, WSL2, macOS, Linux, inside a container) and the Docker state (not installed, daemon stopped, permission needed, WSL integration off, ready) and gives the exact next step. Starts an installer only where a user-level process may (winget, Homebrew) and only with `--yes`; Windows or macOS then show their own approval prompt. Otherwise it prints the steps and a script you run yourself. Exit 0 verified working, 20 handed to you (the window shows *Waiting for you to finish in ...* and a *Re-check* button), 21 consent needed, 1 failed. |",
        "| Isolation and safety | Each source-built tool gets its own environment next to the main one; the clone is staged and moved; a failure removes everything it created and restores a previous working install; https only; no sudo; no piped shell installers. |",
        "",
        "## Per tool",
        "",
        "| Tool | Profile | How installed | Pinned version / revision | Source | Size | Internet | Install time | Verification | CI proof | Status after this change |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    proof_file = ROOT / "config" / "install_proof_result.json"
    proof = json.loads(proof_file.read_text(encoding="utf-8")) if proof_file.is_file() else {"profiles": {}}

    def proof_cell(profile, install_mode):
        if install_mode == "builtin":
            return "n/a (built in)"
        result = proof["profiles"].get(profile)
        if not result:
            return "not yet run"
        label = {"pass": "installed and verified", "expected-manual": "exit 20 with its reason (expected)"}.get(result["status"], "FAILED: " + (result.get("problem") or "see the run"))
        return f"{label}, {result['minutes']} min, {proof['date']} ([run]({proof['run_url']}))"

    for row in rows:
        tool, profile = row["tool"], row["profile"]
        entry = registry.get(profile)
        verify = f"`{row['verify_command']}`"
        if entry and entry["mode"] == "source":
            how = "pinned source checkout + isolated environment (" + ", ".join(s["type"] for s in entry["env"]["steps"]) + ")" if entry["env"]["steps"] else "pinned source checkout (the tool builds its own environments on first use)"
            pin = f"`{entry['commit']}` ({entry['ref']}, resolved {entry['researched']})"
            source = entry["repo"].removesuffix(".git")
            size = f"{entry['download_mb']} MB download, about {entry['disk_gb']} GB disk"
            internet = "yes (" + ", ".join(__import__("source_install").services(entry)) + ")"
            minutes = entry.get("measured_minutes") or entry["minutes"]
            verify = "`" + " ".join(entry["verify"]["argv"]) + "`" + (f" must print {entry['verify']['expect']!r}" if entry["verify"].get("expect") else "")
            status = "automated (consent with --yes)" + ("; " + "; ".join(entry["inputs"][:1]) if entry.get("inputs") else "")
        elif entry:
            how = "manual (verified)"
            pin = f"`{entry['commit']}` ({entry['ref']}, researched {entry['researched']}) for the recipe"
            source = entry["repo"].removesuffix(".git")
            size, internet, minutes = f"{entry['download_mb']} MB source", "yes", "not measured"
            status = "still manual, exit 20: " + entry["manual"]["reason"]
        else:
            facts = CONDA_FACTS.get(profile, ("conda / built in", "-", "-", "not measured"))
            how, source, size, minutes = facts[0], facts[1], facts[2], facts[3]
            pin = "see 'How installed'"
            internet = "none" if row["install_mode"] == "builtin" else "yes (conda, pypi)"
            status = "automated (already)" if row["automated"] == "yes" else "see notes"
        lines.append(f"| {tool} | {profile} | {how} | {pin} | {source} | {size} | {internet} | {minutes} | {verify} | {proof_cell(profile, row['install_mode'])} | {status} |")
    # Docker is a runtime, not an adapter: it has no capability row, so it is described here (python/docker_setup.py, python/tool_installer_registry.py RUNTIME_ROWS).
    lines.append("| docker (container engine) | docker | guided, with consent: `winget install -e --id Docker.DockerDesktop` (Windows, WSL2 through the Windows side), `brew install --cask docker-desktop` (macOS); "
                 "a copyable sudo script from docs.docker.com for Linux and Docker Engine in WSL (never run by PlasBench) | the winget / Homebrew package (not pinned by PlasBench) | https://docs.docker.com/get-started/get-docker/ | "
                 "about 600 MB (not measured) | yes (winget or brew, docker) | not measured | `docker --version` and `docker info` must succeed | " + proof_cell("docker", "guided") +
                 " | exit 0 when Docker is verified working, 20 when steps are handed to you (Docker Desktop's licence is accepted by you, sudo is yours), 21 without consent |")
    manual = {n: e for n, e in registry.items() if e["mode"] == "manual"}
    lines += ["", "## Tools that cannot be installed automatically, with the evidence", ""]
    for name, entry in manual.items():
        lines += [f"### {name}", "", entry["manual"]["reason"], "", "Evidence (fetched " + entry["researched"] + "):"] + [f"- {u}" for u in entry["manual"]["evidence"]]
        lines += ["", "Recipe:"] + [f"{i}. {step}" for i, step in enumerate(entry["manual"]["recipe"], 1)] + [""]
    lines += ["## Inputs the runtime does not include", ""]
    for name, entry in registry.items():
        for item in entry.get("inputs", []):
            lines.append(f"- **{name}**: {item}")
    lines += ["", "## Research record", ""]
    for name, entry in registry.items():
        lines.append(f"- **{name}** ({entry['licence']}): " + ", ".join(entry.get("sources") or entry["manual"]["evidence"]))
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    sys.path.insert(0, str(ROOT / "python"))
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 when docs/TOOL_INSTALL_AUDIT.md is not up to date")
    args = parser.parse_args(argv)
    text = build()
    if args.check:
        current = io.open(OUT, encoding="utf-8", newline="").read() if OUT.is_file() else ""
        if current.replace("\r\n", "\n") != text:
            print("docs/TOOL_INSTALL_AUDIT.md is out of date: run python python/generate_install_audit.py", file=sys.stderr)
            return 1
        return 0
    with io.open(OUT, "w", encoding="utf-8", newline="\n") as handle:   # Path.write_text(newline=) needs Python 3.10
        handle.write(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
