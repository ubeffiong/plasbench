"""The short-read QC panel: a MultiQC-style, interactive view of the QC gate, with a side panel for every sample.

Answers a reviewer's questions on the page: how was read quality assessed, against which thresholds and in which status, what was
excluded and why, do the flagged samples change the conclusion, and how was the assembly selected. It reads only what the pipeline wrote:

  results/short_read_qc.tsv              one row per sample (python/short_read_qc.py)
  results/short_read_qc_status.tsv       the action taken per sample (optional)
  results/assembly_candidates.tsv        the candidate assemblies and the selection (python/assembly_selection.py)
  results/scores.tsv                     only for the flagged-versus-all sensitivity ranking (optional)
  results/short_read_qc.provenance.json  present only when the table is SYNTHETIC (python/make_demo_readqc.py); the panel then says so
  config/short_read_qc_thresholds.tsv    the thresholds (frozen or provisional); its hash is compared with the hash in the QC table

Layout: a left sub-navigation (General statistics, Sequence counts, Read quality, Read length, GC content, Duplication, Adapter content,
Decisions and reasons, Thresholds and policy, Assembly selection). The General statistics table has the MultiQC toolbar: Copy table,
Configure columns, Scatter plot, Violin plot and Export CSV. Clicking a sample (a row or a point) opens a side panel with its full record:
each metric as a gauge against its threshold, the reason it passed, warned or was rejected, the integrity checks, whether it was excluded or
flagged, and its assembly selection.

Every sub-section is also written out in full, statically, in the page: without JavaScript, and in print (the PDF export), all of them are
stacked and open and nothing depends on hidden state. A run without the table shows "Not measured in this run" with what is missing and the
command that produces it, never an empty or invented panel. Standard library only; no external library.
"""
