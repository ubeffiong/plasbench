def stats_table(model):
    head = ["<th data-c='_s' scope='col'>Sample</th>", "<th data-c='_d' scope='col'>Decision</th>"]
    maxima = {c[0]: max([model.value(r, c) or 0 for r in model.qc] + [1e-9]) for c in model.cols}
    for c in model.cols:
        head.append(f"<th data-c='{c[0]}' scope='col'>{esc(c[1])}</th>")
    head.append("<th data-c='_r' scope='col'>Reasons</th>")
    body = []
    for r in model.qc:
        cells = [f"<td data-c='_s' class='rv-l' data-v='{esc(r.get('sample'))}'><button type='button' class='qp-name' data-s='{esc(r.get('sample'))}' "
                 f"aria-label='Open the QC record of {esc(r.get('sample'))}'>{esc(r.get('sample'))}</button></td>",
                 f"<td data-c='_d' data-v='{esc(r.get('qc_status'))}'>{chip(r.get('qc_status'))}</td>"]
        for c in model.cols:
            v = model.value(r, c)
            if v is None:
                cells.append(f"<td data-c='{c[0]}' data-v=''>-</td>")
                continue
            frac = (v * c[3]) / BAR_MAX[c[0]] if c[0] in BAR_MAX else v / maxima[c[0]]
            frac = max(0.0, min(1.0, frac))
            mark = ("~" if c[0] == "pairs" and r.get("pairs_basis") not in ("exact", "", None) else "") + ("*" if c[0] == "depth" and r.get("genome_size_assumed") == "yes" else "")
            label = mark + fmt(v, c[3], c[4])
            cells.append(f"<td data-c='{c[0]}' data-v='{num(v * c[3], 4)}'><div class='rv-bar' title='{esc(label)}'>"
                         f"<span style='width:{100 * frac:.1f}%;background:{BAR_COLOUR[c[0]]}'></span><b>{esc(label)}</b></div></td>")
        cells.append(f"<td data-c='_r' class='rv-l' data-v='{esc(r.get('reasons') or '')}'>{esc(r.get('reasons') or '')}</td>")
        body.append(f"<tr data-s='{esc(r.get('sample'))}'>{''.join(cells)}</tr>")
    return ("<div class='qp-scroll'><table id='qp-gs' class='qp-table'><caption class='qp-cap'>General statistics: one row per sample</caption>"
            f"<thead><tr>{''.join(head)}</tr></thead><tbody>{''.join(body)}</tbody></table></div>"
            "<p class='small'>~ the read-pair total is estimated from the sampled reads; * the depth assumes the default genome size (5 Mb) because none was given. "
            "Bars compare samples within a column. A bar is not a quality grade: the decision and its reason are.</p>")


