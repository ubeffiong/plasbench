def dist_svg(model, col):
    vals = [(r, model.value(r, col)) for r in model.qc]
    vals = [(r, v * col[3]) for r, v in vals if v is not None]
    if not vals:
        return f"<p class='small'>{esc(col[1])}: not measured in this table.</p>"
    t = model.thr(col)
    lims = [x * col[3] for x in ((t["warn"], t["reject"]) if t else ()) if x is not None]
    lo = min([v for _, v in vals] + lims + [0.0] if col[0] not in ("gc", "len", "q") else [v for _, v in vals] + lims)
    hi = max([v for _, v in vals] + lims)
    if hi == lo:
        hi = lo + 1.0
    pad = (hi - lo) * 0.05
    lo, hi = (lo - pad if lo != 0.0 else 0.0), hi + pad
    W, H, L, R, T = 760, 118, 54, 16, 22
    px = lambda x: L + (W - L - R) * (x - lo) / (hi - lo)  # noqa: E731
    s = sorted(v for _, v in vals)
    q1, med, q3 = quantile(s, .25), quantile(s, .5), quantile(s, .75)
    out = [f"<svg class='qp-dist' viewBox='0 0 {W} {H}' role='img' aria-label='{esc(col[1])} of each sample with its thresholds' preserveAspectRatio='xMidYMid meet'>"
           f"<title>{esc(col[1])} across samples</title>"]
    for tk in nice_ticks(lo, hi):
        out.append(f"<line x1='{num(px(tk))}' y1='{T + 4}' x2='{num(px(tk))}' y2='{H - 24}' class='gl'/>"
                   f"<text x='{num(px(tk))}' y='{H - 10}' class='tk'>{esc(tick_label(tk))}</text>")
    out.append(f"<text x='4' y='{T + 26}' font-size='10' fill='currentColor'>{esc(col[1])}</text>")
    out.append(f"<rect x='{num(px(q1))}' y='{T + 4}' width='{num(max(px(q3) - px(q1), 1))}' height='12' fill='rgba(0,114,178,.18)' stroke='#0072B2'>"
               f"<title>quartiles {esc(fmt(q1, 1, col[4]))} to {esc(fmt(q3, 1, col[4]))}, median {esc(fmt(med, 1, col[4]))}</title></rect>"
               f"<line x1='{num(px(med))}' y1='{T + 4}' x2='{num(px(med))}' y2='{T + 16}' stroke='#0072B2' stroke-width='2'/>")
    if t:
        for key, name, colr, dash in (("warn", "warn", "#B07A00", "3 2"), ("reject", "reject", "#D55E00", "")):
            if t[key] is not None:
                x = px(t[key] * col[3])
                dash_attr = f"stroke-dasharray='{dash}'" if dash else ""     # not inside the f-string below: nested quotes need Python 3.12
                out.append(f"<line x1='{num(x)}' y1='{T - 2}' x2='{num(x)}' y2='{H - 24}' stroke='{colr}' stroke-width='1.6' {dash_attr}/>"
                           f"<text x='{num(x)}' y='{T - 6}' class='tk'>{name} {esc(tick_label(round(t[key] * col[3], 4)))}</text>")
    for i, (r, v) in enumerate(vals):
        out.append(point(px(v), T + 36 + (i % 4) * 11, r.get("qc_status"), r.get("sample"), f"{col[1]} {fmt(v, 1, col[4])}, {r.get('qc_status')}"))
    out.append("</svg>")
    return "".join(out)


def scatter_svg(model, cx, cy):
    """Static scatter of two columns (the page script redraws this for any pair): a point per sample, shaped and coloured by decision."""
    pts = [(r, model.value(r, cx) * cx[3], model.value(r, cy) * cy[3]) for r in model.qc if model.value(r, cx) is not None and model.value(r, cy) is not None]
    if not pts:
        return "<p class='small'>Nothing to plot: no sample has both measures.</p>"
    W, H, L, R, T, B = 560, 330, 56, 16, 14, 40
    xs, ys = [p[1] for p in pts], [p[2] for p in pts]
    xlo, xhi, ylo, yhi = min(xs), max(xs), min(ys), max(ys)
    xlo, xhi = (xlo - 1, xhi + 1) if xlo == xhi else (xlo - (xhi - xlo) * .08, xhi + (xhi - xlo) * .08)
    ylo, yhi = (ylo - 1, yhi + 1) if ylo == yhi else (ylo - (yhi - ylo) * .08, yhi + (yhi - ylo) * .08)
    px = lambda x: L + (W - L - R) * (x - xlo) / (xhi - xlo)  # noqa: E731
    py = lambda y: H - B - (H - B - T) * (y - ylo) / (yhi - ylo)  # noqa: E731
    out = [f"<svg class='qp-scatter' viewBox='0 0 {W} {H}' role='img' aria-label='{esc(cy[1])} against {esc(cx[1])}, one point per sample' preserveAspectRatio='xMidYMid meet'>"]
    for tk in nice_ticks(xlo, xhi):
        out.append(f"<line x1='{num(px(tk))}' y1='{T}' x2='{num(px(tk))}' y2='{H - B}' class='gl'/>"
                   f"<text x='{num(px(tk))}' y='{H - B + 14}' class='tk'>{esc(tick_label(tk))}</text>")
    for tk in nice_ticks(ylo, yhi):
        out.append(f"<line x1='{L}' y1='{num(py(tk))}' x2='{W - R}' y2='{num(py(tk))}' class='gl'/>"
                   f"<text x='{L - 4}' y='{num(py(tk) + 3)}' class='te'>{esc(tick_label(tk))}</text>")
    out.append(f"<text x='{(L + W - R) / 2:g}' y='{H - 6}' font-size='11' text-anchor='middle' fill='currentColor'>{esc(cx[1])}</text>"
               f"<text transform='translate(12 {(T + H - B) / 2:g}) rotate(-90)' font-size='11' text-anchor='middle' fill='currentColor'>{esc(cy[1])}</text>")
    for r, x, y in pts:
        out.append(point(px(x), py(y), r.get("qc_status"), r.get("sample"), f"{cx[1]} {fmt(x, 1, cx[4])}, {cy[1]} {fmt(y, 1, cy[4])}, {r.get('qc_status')}"))
    return "".join(out) + "</svg>"


def box_svg(model, col):
    """Static box plot of one column split by decision (the page script offers violins for any column)."""
    groups = {k: [model.value(r, col) * col[3] for r in model.qc if r.get("qc_status") == k and model.value(r, col) is not None] for k in ("PASS", "WARN", "REJECT")}
    groups = {k: v for k, v in groups.items() if v}
    if not groups:
        return "<p class='small'>Nothing to plot.</p>"
    allv = [v for g in groups.values() for v in g]
    lo, hi = min(allv), max(allv)
    lo, hi = (lo - 1, hi + 1) if lo == hi else (lo - (hi - lo) * .08, hi + (hi - lo) * .08)
    W, H, L, T, B = 560, 280, 56, 14, 36
    py = lambda y: H - B - (H - B - T) * (y - lo) / (hi - lo)  # noqa: E731
    out = [f"<svg class='qp-violin' viewBox='0 0 {W} {H}' role='img' aria-label='{esc(col[1])} by decision' preserveAspectRatio='xMidYMid meet'>"]
    for tk in nice_ticks(lo, hi):
        out.append(f"<line x1='{L}' y1='{num(py(tk))}' x2='{W - 10}' y2='{num(py(tk))}' class='gl'/>"
                   f"<text x='{L - 4}' y='{num(py(tk) + 3)}' class='te'>{esc(tick_label(tk))}</text>")
    t = model.thr(col)
    if t:
        for key, colr in (("warn", "#B07A00"), ("reject", "#D55E00")):
            if t[key] is not None and lo <= t[key] * col[3] <= hi:
                out.append(f"<line x1='{L}' y1='{num(py(t[key] * col[3]))}' x2='{W - 10}' y2='{num(py(t[key] * col[3]))}' stroke='{colr}' stroke-width='1.5' stroke-dasharray='4 3'/>"
                           f"<text x='{W - 12}' y='{num(py(t[key] * col[3]) - 3)}' class='te'>{key}</text>")
    step = (W - L - 20) / (len(groups) + 0.0)
    for i, (k, g) in enumerate(groups.items()):
        s = sorted(g)
        cxm = L + step * (i + 0.5)
        q1, med, q3 = quantile(s, .25), quantile(s, .5), quantile(s, .75)
        out.append(f"<rect x='{num(cxm - 22)}' y='{num(py(q3))}' width='44' height='{num(max(py(q1) - py(q3), 1))}' fill='{STATUS_COLOUR[k]}' fill-opacity='.35' stroke='{STATUS_COLOUR[k]}'>"
                   f"<title>{k}: n {len(s)}, median {esc(fmt(med, 1, col[4]))}, quartiles {esc(fmt(q1, 1, col[4]))} to {esc(fmt(q3, 1, col[4]))}</title></rect>"
                   f"<line x1='{num(cxm - 22)}' y1='{num(py(med))}' x2='{num(cxm + 22)}' y2='{num(py(med))}' stroke='currentColor' stroke-width='2'/>"
                   f"<text x='{num(cxm)}' y='{H - 18}' font-size='11' text-anchor='middle' fill='currentColor'>{k} (n {len(s)})</text>")
    return "".join(out) + "</svg>"


