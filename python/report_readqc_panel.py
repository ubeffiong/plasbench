# ------------------------------------------------------------------------------------------------ reading
def number(value):
    try:
        x = float(value)
    except (TypeError, ValueError):
        return None
    return x if x == x and x not in (float("inf"), float("-inf")) else None


def read_tsv(path):
    if not path or not os.path.isfile(path) or os.path.getsize(path) == 0:
        return None
    try:
        with open(path, newline="", encoding="utf-8") as handle:
            return list(csv.DictReader((line for line in handle if line.strip() and not line.startswith("#")), delimiter="\t")) or None
    except (OSError, UnicodeDecodeError, csv.Error):
        return None


def load_thresholds(path=THRESHOLDS):
    """{'rows': [...], 'sha': 12 hex of the file, 'policy': frozen|provisional, 'frozen_on': text or ''} or None when the file is absent."""
    if not path or not os.path.isfile(path):
        return None
    raw = open(path, "rb").read()
    rows = read_tsv(path) or []
    out = []
    for r in rows:
        out.append({"metric": r.get("metric", ""), "direction": r.get("direction", "min"), "warn": number(r.get("warn")),
                    "reject": number(r.get("reject")), "status": (r.get("status") or "").strip(), "why": r.get("rationale", "")})
    policy = "frozen" if out and all(t["status"] == "frozen" for t in out) else "provisional"
    found = re.search(rb"FROZEN on ([^.;]*?) from", raw)
    return {"rows": out, "sha": hashlib.sha256(raw).hexdigest()[:12], "policy": policy, "frozen_on": found.group(1).decode() if found else ""}


def judge(value, t):
    """'pass' | 'warn' | 'reject' for one value against one threshold row, the rule short_read_qc.decide() applies (reject is tested first)."""
    if value is None or t is None:
        return None
    for level, name in (("reject", "reject"), ("warn", "warn")):
        limit = t[level]
        if limit is None:
            continue
        if (value < limit) if t["direction"] == "min" else (value > limit):
            return name
    return "pass"


def read_json(path):
    try:
        with open(path, encoding="utf-8") as handle:
            return json.load(handle)
    except (OSError, ValueError):
        return None


def is_synthetic(results_dir):
    """True when the QC table was written by the demo generator (its provenance file says so) or every sample of the run is marked synthetic."""
    if not results_dir:
        return False
    prov = read_json(os.path.join(results_dir, "short_read_qc.provenance.json"))
    if isinstance(prov, dict) and prov.get("synthetic") is True:
        return True
    try:
        import data_nature
        sheet = data_nature.read_sheet(os.path.join(results_dir, "samples.tsv"))
        return bool(sheet) and all(data_nature.is_synthetic(row) for row in sheet.values())
    except Exception:  # noqa: BLE001 - the marker is advisory; a failure to read it must not break the report
        return False


# ------------------------------------------------------------------------------------------------ small drawing helpers
def fmt(value, scale=1, decimals=1):
    if value is None:
        return "-"
    v = value * scale
    if decimals == 0 and abs(v) >= 1e6:
        return f"{v / 1e6:.2f} M"
    if decimals == 0 and abs(v) >= 1e4:
        return f"{v / 1e3:.0f} k"
    return f"{v:.{decimals}f}" if decimals else f"{v:,.0f}"


