def sensitivity_block(model):
    """Mean F1 per tool with every scored sample and without the flagged ones, or the reason it is not computed. Descriptive; never a ranking rule."""
    flagged = {r.get("sample") for r in model.qc if r.get("qc_status") in ("WARN", "REJECT")}
    if not flagged:
        return "<p>No sample was flagged, so there is nothing to leave out: the flagged-sample sensitivity analysis has no effect on the conclusion.</p>"
    if not model.scores:
        return ("<p><b>Not computed.</b> It needs results/scores.tsv beside the QC table to rank the tools with and without the "
                f"{len(flagged)} flagged sample(s); that file was not found.</p>")
    qc_samples = {r.get("sample") for r in model.qc}
    per = {}
    for r in model.scores:
        f1 = number(r.get("f1"))
        if r.get("sample") in qc_samples and f1 is not None and r.get("tool"):
            per.setdefault(r["tool"], {})[r["sample"]] = f1
    scored = {s for d in per.values() for s in d}
    kept = scored - flagged
    if not per or not (scored & flagged):
        return ("<p><b>Not computed.</b> None of the flagged samples has a scored result, so leaving them out changes nothing that could be ranked here.</p>"
                if per else "<p><b>Not computed.</b> results/scores.tsv has no F1 per sample and tool for the samples in the QC table.</p>")
    if not kept:
        return "<p><b>Not computed.</b> Every scored sample is flagged, so there is no unflagged set to compare with.</p>"
    mean = lambda d, keep: (sum(d[s] for s in d if s in keep) / max(1, sum(1 for s in d if s in keep))) if any(s in keep for s in d) else None  # noqa: E731
    all_m = {t: mean(d, scored) for t, d in per.items()}
    kept_m = {t: mean(d, kept) for t, d in per.items()}
    order = lambda m: {t: i + 1 for i, t in enumerate(sorted((t for t in m if m[t] is not None), key=lambda t: (-m[t], t)))}  # noqa: E731
    ra, rk = order(all_m), order(kept_m)
    changed = [t for t in ra if rk.get(t) != ra[t]]
    rows = "".join(f"<tr><td>{esc(t)}</td><td>{all_m[t]:.3f}</td><td>{ra.get(t, '-')}</td><td>{('%.3f' % kept_m[t]) if kept_m.get(t) is not None else '-'}</td>"
                   f"<td>{rk.get(t, '-')}</td><td>{'changed' if t in changed else 'same'}</td></tr>" for t in sorted(per, key=lambda t: ra.get(t, 99)))
    first_all = next((t for t, i in ra.items() if i == 1), None)
    first_kept = next((t for t, i in rk.items() if i == 1), None)
    verdict_text = ("The order of the tools is the same with and without the flagged samples." if not changed else
                    f"The order differs for {len(changed)} tool(s)" + (f", and the top tool changes from {esc(first_all)} to {esc(first_kept)}." if first_all != first_kept else f"; the top tool stays {esc(first_all)}."))
    return (f"<p>{len(flagged & scored)} flagged sample(s) with results, {len(kept)} unflagged. {verdict_text} Mean F1 per tool; descriptive, not the headline ranking "
            "(the leaderboard's own rule decides that).</p><div class='qp-scroll'><table class='qp-table'><thead><tr><th>Tool</th><th>Mean F1, all</th><th>Rank</th>"
            f"<th>Mean F1, without flagged</th><th>Rank</th><th>Order</th></tr></thead><tbody>{rows}</tbody></table></div>"
            + ("<p class='small'>The samples are synthetic: this is a demonstration of the check, not a finding.</p>" if model.synthetic else ""))


