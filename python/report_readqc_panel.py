def state_chip(state, mark):
    return f" <span class='rv-chip {mark}'>{esc(state.upper())}</span>" if state else ""


def chip(status):
    cls = {"PASS": "rv-pass", "WARN": "rv-warn", "REJECT": "rv-reject"}.get(status, "")
    return f"<span class='rv-chip {cls}'>{esc(status or '-')}</span>"


def marker(x, y, status, r=5, extra=""):
    """A point whose shape also names its decision (circle PASS, triangle WARN, square REJECT), so colour is never the only channel."""
    if status == "WARN":
        return f"<polygon points='{num(x)},{num(y - r - 1)} {num(x + r + 1)},{num(y + r)} {num(x - r - 1)},{num(y + r)}' class='f{esc(status[:1])}' {extra}>"
    if status == "REJECT":
        return f"<rect x='{num(x - r)}' y='{num(y - r)}' width='{num(2 * r)}' height='{num(2 * r)}' class='f{esc(status[:1])}' {extra}>"
    return f"<circle cx='{num(x)}' cy='{num(y)}' r='{num(r)}' class='f{esc(status[:1])}' {extra}>"


def point(x, y, status, sample, label):
    tag = marker(x, y, status)
    closing = "</polygon>" if tag.startswith("<polygon") else ("</rect>" if tag.startswith("<rect") else "</circle>")
    return (f"<g class='qp-pt' data-s='{esc(sample)}' tabindex='0' role='button'>"
            f"{tag}<title>{esc(sample)}: {esc(label)}</title>{closing}</g>")


def quantile(sorted_values, p):
    if not sorted_values:
        return None
    k = (len(sorted_values) - 1) * p
    lo, hi = int(math.floor(k)), int(math.ceil(k))
    return sorted_values[lo] + (sorted_values[hi] - sorted_values[lo]) * (k - lo)


def nice_ticks(lo, hi, n=5):
    if hi <= lo:
        return [lo]
    raw = (hi - lo) / n
    mag = 10 ** math.floor(math.log10(raw))
    step = next(m * mag for m in (1, 2, 2.5, 5, 10) if m * mag >= raw)
    first = math.ceil(lo / step) * step
    out, v = [], first
    while v <= hi + step * 1e-9 and len(out) < 12:
        out.append(round(v, 10))
        v += step
    return out


def tick_label(v):
    return f"{v:g}" if abs(v) < 1e4 else (f"{v / 1e6:g}M" if abs(v) >= 1e6 else f"{v / 1e3:g}k")


# ------------------------------------------------------------------------------------------------ the model
class Model:
    """Everything the panel shows, computed once from the tables."""

    def __init__(self, qc, thresholds, status_rows=None, candidates=None, scores=None, synthetic=False, results_dir=""):
        self.qc = sorted(qc, key=lambda r: ({"REJECT": 0, "WARN": 1, "PASS": 2}.get(r.get("qc_status"), 3), r.get("sample", "")))
        self.th = thresholds
        self.status_rows = {r.get("sample"): r for r in (status_rows or [])}
        self.cands = candidates or []
        self.scores = scores
        self.synthetic = synthetic
        self.results_dir = results_dir
        self.cols = [c for c in COLS if any(number(r.get(c[2])) is not None for r in self.qc)]
        self.by_metric = {t["metric"]: t for t in (thresholds["rows"] if thresholds else [])}
        self.asm = {}
        for r in self.cands:
            self.asm.setdefault(r.get("sample"), []).append(r)

    def value(self, r, col):
        return number(r.get(col[2]))

    def thr(self, col):
        return self.by_metric.get(col[5]) if col[5] else None

    def action(self, r):
        s = self.status_rows.get(r.get("sample"))
        return s.get("action") if s else ""

    def payload(self):
        """Compact JSON for the page script: columns, one row per sample, thresholds in display units."""
        thr = {}
        for c in self.cols:
            t = self.thr(c)
            if t:
                thr[c[0]] = [t["direction"], None if t["warn"] is None else t["warn"] * c[3], None if t["reject"] is None else t["reject"] * c[3]]
        rows = [[r.get("sample"), r.get("qc_status")] + [None if self.value(r, c) is None else round(self.value(r, c) * c[3], 4) for c in self.cols] for r in self.qc]
        return {"cols": [[c[0], c[1], c[3], c[4]] for c in self.cols], "rows": rows, "thr": thr, "syn": 1 if self.synthetic else 0}


# ------------------------------------------------------------------------------------------------ gauges and records
def gauge_svg(value, t, scale, decimals, label):
    """One metric as a gauge: coloured zones (reject, warn, pass) from the thresholds, the value as a marker, limits as labelled ticks."""
    W, H, L, R = 360, 46, 8, 8
    if value is None or t is None:
        return ""
    v = value * scale
    warn = None if t["warn"] is None else t["warn"] * scale
    rej = None if t["reject"] is None else t["reject"] * scale
    limits = [x for x in (warn, rej) if x is not None]
    if t["direction"] == "min":
        lo, hi = 0.0, max(v, max(limits)) * 1.25 or 1.0
        zones = []
        if rej is not None:
            zones.append((lo, rej, "reject"))
        zones += [(rej if rej is not None else lo, warn, "warn")] if warn is not None else []
        zones.append((warn if warn is not None else (rej or lo), hi, "pass"))
    else:
        lo = 0.0
        hi = max(v, max(limits) * 1.5 if limits else 1.0) * 1.12 or 1.0
        zones = [(lo, warn, "pass")] if warn is not None else []
        if rej is not None:
            zones += [(warn if warn is not None else lo, rej, "warn"), (rej, hi, "reject")]
        elif warn is not None:
            zones.append((warn, hi, "warn"))
    px = lambda x: L + (W - L - R) * (x - lo) / (hi - lo)  # noqa: E731
    out = [f"<svg class='qp-gauge' viewBox='0 0 {W} {H}' role='img' aria-label='{esc(label)} {esc(fmt(value, scale, decimals))} against its limits'>"]
    for a, b, kind in zones:
        if b > a:
            out.append(f"<rect x='{num(px(a), 1)}' y='10' width='{num(px(b) - px(a), 1)}' height='14' class='z{kind[0]}'/>")
    for limit, name in ((warn, "warn"), (rej, "reject")):
        if limit is not None:
            out.append(f"<line x1='{num(px(limit), 1)}' y1='7' x2='{num(px(limit), 1)}' y2='27' class='l{name[0]}'/>"
                       f"<text x='{num(px(limit), 1)}' y='38' class='gt'>{name} {tick_label(round(limit, 4))}</text>")
    x = px(min(max(v, lo), hi))
    out.append(f"<path d='M{num(x, 1)} 25V9M{num(x - 5, 1)} 2h10l-5 7z' class='gv'/></svg>")
    return "".join(out)


def verdict(value, t, scale, decimals, label):
    """The reason, in words, that a metric passed, warned or was rejected."""
    if value is None:
        return "not measured", None
    state = judge(value, t)
    v = fmt(value, scale, decimals)
    op_bad, op_ok = ("<", ">=") if t["direction"] == "min" else (">", "<=")
    unit = lambda x: fmt(x, scale, decimals)  # noqa: E731
    if state == "reject":
        return f"rejected: {v} {op_bad} the reject limit {unit(t['reject'])}", state
    if state == "warn":
        return f"warned: {v} {op_bad} the warn limit {unit(t['warn'])}", state
    parts = [f"{op_ok} the warn limit {unit(t['warn'])}"] if t["warn"] is not None else []
    if t["reject"] is None and t["warn"] is not None:
        parts.append("no reject limit")
    return f"passed: {v} {', '.join(parts) or 'within its limits'}", state


def assembly_outcome(model, sample):
    rows = model.asm.get(sample)
    if not rows:
        return "<p class='small'>No assembly candidate record for this sample.</p>"
    chosen = next((r for r in rows if r.get("selected") == "yes"), None)
    reason = next((r.get("selection_reason") for r in rows if r.get("selection_reason")), "")
    head = (f"<p><b>Selected: {esc(chosen['assembler'])}</b> (N50 {esc(chosen.get('n50') or '-')}, {esc(chosen.get('n_contigs') or '-')} contigs). {esc(reason)}</p>"
            if chosen else f"<p><b>No eligible assembly was selected.</b> {esc(reason)}</p>")
    items = "".join(f"<li>{esc(r['assembler'])}: {'eligible' if r.get('eligible') == 'yes' else 'not eligible'}"
                    f"{(' (' + esc(r.get('reasons')) + ')') if r.get('reasons') else ''}{' &#9733;' if r is chosen else ''}</li>" for r in rows)
    return head + f"<ul class='qp-list'>{items}</ul>"


def action_text(model, r):
    status, act = r.get("qc_status"), model.action(r)
    if r.get("integrity") not in ("ok", "", None):
        base = f"Integrity failed ({r.get('integrity')}): a read set that cannot be read is excluded whatever the mode."
    elif status == "PASS":
        base = "Passed every limit: proceeds to assembly and the primary benchmark."
    elif status == "WARN":
        base = "Flagged: proceeds, and belongs in the sensitivity analysis."
    elif status == "REJECT":
        base = "Rejected: excluded from the primary benchmark when SHORT_READ_QC_MODE=enforce; kept and flagged when it is report."
    else:
        base = "No decision recorded."
    if act:
        base += f" Action recorded in this run: {act}."
    elif status in ("WARN", "REJECT"):
        base += " This run recorded no action (no short_read_qc_status.tsv), so the mode it ran in is not known."
    return base


def record_card(model, r):
    """One sample's full QC record, as written for the side panel and for print."""
    s, status = r.get("sample"), r.get("qc_status")
    ok = r.get("integrity") in ("ok", "", None)
    rows = []
    for c in model.cols:
        t = model.thr(c)
        v = model.value(r, c)
        text, state = verdict(v, t, c[3], c[4], c[1]) if t else (("no threshold" if v is not None else "not measured"), None)
        mark = {"pass": "rv-pass", "warn": "rv-warn", "reject": "rv-reject"}.get(state, "")
        shown = f"{fmt(v, c[3], c[4])}" + ("*" if c[0] == "depth" and r.get("genome_size_assumed") == "yes" else "") + ("~" if c[0] == "pairs" and r.get("pairs_basis") not in ("exact", "", None) else "")
        rows.append(f"<div class='qp-g'><div class='qp-gh'><b>{esc(c[1])}</b> <span>{esc(shown)}</span>"
                    f"{state_chip(state, mark)}</div>"
                    f"{gauge_svg(v, t, c[3], c[4], c[1]) if t else ''}<div class='small'>{esc(text)}</div></div>")
    checks = [("File integrity", r.get("integrity") or "-"), ("Read-pair count", f"{r.get('pairs_basis') or '-'}" + (" (estimated from the sampled reads)" if r.get("pairs_basis") == "estimated" else "")),
              ("Genome size for depth", f"{r.get('genome_size_mb') or '-'} Mb" + (" (assumed default, none given)" if r.get("genome_size_assumed") == "yes" else "")),
              ("Pairs sampled", r.get("read_pairs_sampled") or "-"), ("Contamination screen", (r.get("contamination_screen") or "not_evaluated") + " (needs a database; not done here)")]
    integ = "".join(f"<tr><th class='rv-l'>{esc(k)}</th><td class='rv-l'>{esc(v)}</td></tr>" for k, v in checks)
    reasons = r.get("reasons") or ("none: every limit met" if ok else "")
    return (f"<div class='qp-rec' data-s='{esc(s)}'><h4>{esc(s)} {chip(status)}</h4>"
            f"{SYN_REC if model.synthetic else ''}"
            f"<p><b>Why:</b> {esc(reasons)}</p><p>{esc(action_text(model, r))}</p>"
            f"<h5>Each metric against its threshold</h5>{''.join(rows) or '<p class=small>No metric was measured.</p>'}"
            f"<h5>Integrity checks</h5><table class='qp-kv'><tbody>{integ}</tbody></table>"
            f"<h5>Assembly selection outcome</h5>{assembly_outcome(model, s)}"
            f"<p class='small'>Thresholds {esc(r.get('policy_status') or 'not recorded')}, file hash {esc(r.get('thresholds_sha') or 'not recorded')}.</p></div>")


